-- Докупленный день смены.
--
-- Семья, взявшая самый большой пакет и потратившая его, хочет ещё пару
-- дней — а покупать второй пакет незачем и дорого. Цена такого дня своя,
-- ниже разовой, и живёт она у смены: у каждой она может быть своя, как
-- и цена дня и сами пакеты.
alter table studio_groups
  add column if not exists extra_price numeric(10,2);
