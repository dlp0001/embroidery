import { connectTelegram } from '@/app/account/actions';

/**
 * Полоска в «Неделе» для тех, кто бота ещё не подключил. Кнопка есть в
 * профиле и внизу, в «Написать студии», но туда не доходят: после письма
 * подключились семеро, а двое заходили в кабинет и кнопку не заметили.
 *
 * Нарочно одна строка и тихая кнопка: это приглашение, а не требование,
 * и экран принадлежит занятиям. Подключился — полоска пропала, никаких
 * «скрыть на время» заводить не нужно.
 */
export default function BotNudge() {
  return (
    <div
      className="note"
      style={{
        display: 'flex', alignItems: 'center', justifyContent: 'space-between',
        // На узком экране кнопка уходит под текст: она шире, чем кажется,
        // и в одну строку с фразой на телефоне не встаёт.
        flexWrap: 'wrap', gap: 10, marginBottom: 14,
        // Теснее обычной «заметки»: это полоска, а не блок с объяснением.
        padding: '12px 14px',
      }}
    >
      <span>Бот напомнит о занятии и запишет в одно нажатие.</span>
      <form action={connectTelegram}>
        <button className="btn-quiet" type="submit">Подключить телеграм</button>
      </form>
    </div>
  );
}
